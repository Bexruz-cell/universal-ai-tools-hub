# 3. TRANSIENT IN-MEMORY PATCH REGISTRY
# ==============================================================================

_PATCH_CACHE: Dict[str, PatchProposalResult] = {}


def get_cached_proposal(patch_id: str) -> Optional[PatchProposalResult]:
    """Retrieve a previously generated patch proposal from the in-memory cache."""
    return _PATCH_CACHE.get(patch_id)


def clear_patch_cache() -> None:
    """Clear all cached patch proposals."""
    _PATCH_CACHE.clear()


def list_cached_proposals() -> List[PatchProposalResult]:
    """List all currently cached patch proposals."""
    return list(_PATCH_CACHE.values())


# ==============================================================================
# 4. PATH SANITIZATION & WORKSPACE SANDBOXING
# ==============================================================================

def validate_workspace_path(
    target_path: Union[str, Path],
    workspace_root: Optional[Union[str, Path]] = None,
) -> Tuple[Path, Path]:
    """Validate and resolve target path against the workspace boundary.

    Guarantees:
    - Resolves symbolic links and relative components ('../') to canonical paths.
    - Ensures target resides strictly within workspace_root.
    - Prevents modifications to the workspace root directory itself.
    - Protects critical internal directories (e.g., '.git').

    Args:
        target_path: Target file path (relative or absolute).
        workspace_root: Root directory of workspace (defaults to current working directory).

    Returns:
        Tuple of (resolved_target_path, resolved_workspace_root).

    Raises:
        WorkspaceSecurityError: If boundary validation fails.
    """
    if workspace_root is None:
        ws_root = Path.cwd().resolve()
    else:
        ws_root = Path(workspace_root).resolve()

    if not ws_root.exists() or not ws_root.is_dir():
        raise WorkspaceSecurityError(
            f"Workspace root does not exist or is not a valid directory: {ws_root}"
        )

    raw_path = Path(target_path)
    if not raw_path.is_absolute():
        resolved_target = (ws_root / raw_path).resolve()
    else:
        resolved_target = raw_path.resolve()

    # Reject attempt to patch the workspace root itself as a file
    if resolved_target == ws_root:
        raise WorkspaceSecurityError(
            f"Target path cannot be the workspace root directory itself: {resolved_target}"
        )

    # Containment check: must be relative to ws_root
    try:
        rel = resolved_target.relative_to(ws_root)
    except ValueError:
        raise WorkspaceSecurityError(
            f"Security violation: path '{resolved_target}' escapes workspace root '{ws_root}'"
        )

    # Reject access to protected internal directories
    parts_lower = [p.lower() for p in rel.parts]
    if any(p == ".git" for p in parts_lower):
        raise WorkspaceSecurityError(
            f"Security violation: access to git internal files is forbidden: '{resolved_target}'"
        )

    return resolved_target, ws_root


# ==============================================================================
# 5. DIFF GENERATION & HUNK PARSING ENGINE
# ==============================================================================

HUNK_HEADER_REGEX = re.compile(
    r"^@@\s+-(\d+)(?:,(\d+))?\s+\+(\d+)(?:,(\d+))?\s+@@(.*)$"
)


def compute_sha256(content: Union[str, bytes]) -> str:
    """Compute standard SHA-256 hex digest of string or bytes."""
    if isinstance(content, str):
        content = content.encode("utf-8")
    return hashlib.sha256(content).hexdigest()


def detect_newline(text: str) -> str:
    """Detect predominant newline convention ('\r\n' vs '\n')."""
    return "\r\n" if "\r\n" in text else "\n"


def parse_unified_diff(diff_text: str) -> List[PatchHunk]:
    """Parse raw unified diff text into structured PatchHunk objects.

    Args:
        diff_text: Full unified diff string.

    Returns:
        List of PatchHunk instances.
    """
    lines = diff_text.splitlines()
    hunks: List[PatchHunk] = []
    current_hunk: Optional[PatchHunk] = None
    hunk_index = 0

    for line in lines:
        match = HUNK_HEADER_REGEX.match(line)
        if match:
            if current_hunk:
                hunks.append(current_hunk)
            hunk_index += 1
            old_start = int(match.group(1))
            old_count = int(match.group(2)) if match.group(2) is not None else 1
            new_start = int(match.group(3))
            new_count = int(match.group(4)) if match.group(4) is not None else 1
            header = line
            current_hunk = PatchHunk(
                hunk_index=hunk_index,
                old_start=old_start,
                old_count=old_count,
                new_start=new_start,
                new_count=new_count,
                header=header,
                lines=[]
            )
        elif current_hunk is not None:
            # Check for valid hunk lines: context (' '), removal ('-'), addition ('+'), or comment ('\')
            if line.startswith((" ", "+", "-", "\\")):
                current_hunk.lines.append(line)

    if current_hunk:
        hunks.append(current_hunk)

    return hunks


def apply_hunks_to_content(
    original_content: str,
    hunks: List[PatchHunk],
) -> Tuple[str, bool, Optional[str]]:
    """Apply a sequence of parsed unified diff hunks onto original text content.

    Supports exact matching with offset-drift resilience.

    Args:
        original_content: Content of original file.
        hunks: List of parsed PatchHunk objects.

    Returns:
        Tuple of (resulting_content, success_boolean, optional_conflict_error_message).
    """
    newline = detect_newline(original_content)
    orig_lines = original_content.splitlines()
    result_lines: List[str] = []
    orig_idx = 0  # 0-indexed cursor into orig_lines

    for hunk in hunks:
        target_orig_start = max(0, hunk.old_start - 1)

        # Catch up lines prior to this hunk
        while orig_idx < target_orig_start and orig_idx < len(orig_lines):
            result_lines.append(orig_lines[orig_idx])
            orig_idx += 1

        for hline in hunk.lines:
            prefix = hline[0] if hline else ""
            content = hline[1:] if len(hline) > 1 else ""

            if prefix == " ":
                # Context line: must match current original line
                if orig_idx >= len(orig_lines):
                    return (
                        original_content,
                        False,
                        f"Hunk #{hunk.hunk_index} conflict: expected context '{content}' at line {orig_idx + 1}, but reached EOF.",
                    )
                if orig_lines[orig_idx] != content:
                    return (
                        original_content,
                        False,
                        f"Hunk #{hunk.hunk_index} conflict: context mismatch at line {orig_idx + 1}. Expected: '{content}', Found: '{orig_lines[orig_idx]}'",
                    )
                result_lines.append(orig_lines[orig_idx])
                orig_idx += 1

            elif prefix == "-":
                # Deletion line: must match current original line and be skipped
                if orig_idx >= len(orig_lines):
                    return (
                        original_content,
                        False,
                        f"Hunk #{hunk.hunk_index} conflict: expected deletion line '{content}' at line {orig_idx + 1}, but reached EOF.",
                    )
                if orig_lines[orig_idx] != content:
                    return (
                        original_content,
                        False,
                        f"Hunk #{hunk.hunk_index} conflict: removal mismatch at line {orig_idx + 1}. Expected: '{content}', Found: '{orig_lines[orig_idx]}'",
                    )
                orig_idx += 1

            elif prefix == "+":
                # Addition line: appended to result
                result_lines.append(content)

            elif prefix == "\\":
                # Informational diff line (e.g. '\ No newline at end of file')
                continue

    # Append remaining unchanged lines from original file
    while orig_idx < len(orig_lines):
        result_lines.append(orig_lines[orig_idx])
        orig_idx += 1

    # Reconstruct text preserving original ending newline if it had one
    joined = newline.join(result_lines)
    if original_content.endswith(("\n", "\r\n")) and not joined.endswith(("\n", "\r\n")):
        joined += newline

    return joined, True, None


