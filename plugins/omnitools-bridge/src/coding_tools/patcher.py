# ==============================================================================
# 1. EXCEPTION DEFINITIONS
# ==============================================================================

class PatchError(Exception):
    """Base exception for all safe patch operations."""
    pass


class WorkspaceSecurityError(PatchError):
    """Raised when target file path escapes the workspace root sandbox."""
    pass


class ConfirmationRequiredError(PatchError):
    """Raised when apply_patch is executed without explicit user/agent confirmation."""
    pass


class PatchConflictError(PatchError):
    """Raised when diff hunks cannot be cleanly reconciled against target content."""
    pass


class SyntaxVerificationError(PatchError):
    """Raised when patched content fails language syntax or structural validation."""
    pass


class BinaryFileError(PatchError):
    """Raised when patch operation is attempted on a binary file."""
    pass


# ==============================================================================
# 2. DATA STRUCTURES & MODELS
# ==============================================================================

@dataclass
class PatchHunk:
    """Represents a parsed unified diff hunk."""
    hunk_index: int
    old_start: int
    old_count: int
    new_start: int
    new_count: int
    header: str
    lines: List[str]

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class PatchMetadata:
    """Detailed audit metadata describing diff volume, lineage, and cryptographic hashes."""
    patch_id: str
    file_path: str
    workspace_root: str
    timestamp: str
    lines_added: int
    lines_removed: int
    hunk_count: int
    original_sha256: Optional[str]
    proposed_sha256: str
    is_new_file: bool = False
    is_deletion: bool = False

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class PatchProposalResult:
    """Strictly read-only preview result generated by propose_patch."""
    patch_id: str
    file_path: str
    diff: str
    metadata: PatchMetadata
    can_apply_cleanly: bool
    hunks: List[PatchHunk]
    proposed_content: str
    conflict_reason: Optional[str] = None
    preview_summary: str = ""

    def to_dict(self) -> Dict[str, Any]:
        data = asdict(self)
        # Omit massive proposed_content from default lightweight serialization if needed
        return data


@dataclass
class PatchApplyResult:
    """Detailed outcome of an apply_patch operation including backup and verification status."""
    success: bool
    patch_id: str
    file_path: str
    backup_path: Optional[str]
    syntax_check_passed: bool
    syntax_error: Optional[str]
    rolled_back: bool
    applied_hunks: int
    total_hunks: int
    message: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


