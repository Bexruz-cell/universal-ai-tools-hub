# 6. SYNTAX & STRUCTURAL VERIFICATION
# ==============================================================================

def verify_syntax(file_path: Union[str, Path], content: str) -> Tuple[bool, Optional[str]]:
    """Validate content syntax based on target file extension.

    Supported validations:
    - Python (.py): ast.parse() abstract syntax tree compilation.
    - JSON (.json): json.loads() schema structure check.

    Args:
        file_path: Target path to derive file format.
        content: Code/data content to validate.

    Returns:
        Tuple of (is_valid_boolean, optional_error_message).
    """
    path = Path(file_path)
    suffix = path.suffix.lower()

    if suffix == ".py":
        try:
            ast.parse(content, filename=str(path))
            return True, None
        except SyntaxError as e:
            err_line = e.lineno or 0
            err_col = e.offset or 0
            return (
                False,
                f"SyntaxError in {path.name} at line {err_line}, col {err_col}: {e.msg}",
            )
        except Exception as e:
            return False, f"Python parse error in {path.name}: {str(e)}"

    elif suffix == ".json":
        try:
            json.loads(content)
            return True, None
        except json.JSONDecodeError as e:
            return (
                False,
                f"JSONDecodeError in {path.name} at line {e.lineno}, col {e.colno}: {e.msg}",
            )

    # For unknown/unsupported extensions, pass by default
    return True, None


# ==============================================================================
# 7. PROPOSE_PATCH (STRICTLY READ-ONLY)
# ==============================================================================

def propose_patch(
    file_path: Union[str, Path],
    new_content: Optional[str] = None,
    patch_diff: Optional[str] = None,
    workspace_root: Optional[Union[str, Path]] = None,
) -> PatchProposalResult:
    """Generate a unified diff preview and patch proposal. Strictly read-only.

    Under NO circumstances will this function create, modify, truncate, or touch
    any file on disk.

    Args:
        file_path: Path to target file (relative to workspace or absolute).
        new_content: Full proposed new content of the target file.
        patch_diff: Raw unified diff string to apply.
        workspace_root: Workspace root directory (defaults to current working directory).

    Returns:
        PatchProposalResult containing diff preview, hunks, checksums, and patch ID.

    Raises:
        WorkspaceSecurityError: If target path escapes workspace boundary.
        ValueError: If neither new_content nor patch_diff is provided.
    """
    if new_content is None and patch_diff is None:
        raise ValueError("Either 'new_content' or 'patch_diff' must be provided to propose_patch.")

    target_path, ws_root = validate_workspace_path(file_path, workspace_root)
    rel_path_str = str(target_path.relative_to(ws_root)).replace("\\", "/")

    # Read existing content if file exists
    is_new_file = not target_path.exists()
    original_content = ""
    original_sha256: Optional[str] = None

    if not is_new_file:
        try:
            original_content = target_path.read_text(encoding="utf-8")
            original_sha256 = compute_sha256(original_content)
        except UnicodeDecodeError:
            raise BinaryFileError(f"Target file appears to be binary: {target_path}")

    # Determine proposed content and diff
    can_apply_cleanly = True
    conflict_reason: Optional[str] = None
    final_diff: str = ""
    proposed_content: str = ""

    if new_content is not None:
        proposed_content = new_content
        newline = detect_newline(original_content if original_content else proposed_content)
        
        # Build unified diff
        orig_split = original_content.splitlines(keepends=True)
        new_split = proposed_content.splitlines(keepends=True)
        from_file = f"/dev/null" if is_new_file else f"a/{rel_path_str}"
        to_file = f"b/{rel_path_str}"

        diff_gen = difflib.unified_diff(
            orig_split,
            new_split,
            fromfile=from_file,
            tofile=to_file,
            lineterm=newline,
        )
        final_diff = "".join(diff_gen)

    elif patch_diff is not None:
        final_diff = patch_diff
        hunks_parsed = parse_unified_diff(patch_diff)
        patched_text, success, conflict = apply_hunks_to_content(original_content, hunks_parsed)
        if success:
            proposed_content = patched_text
        else:
            can_apply_cleanly = False
            conflict_reason = conflict
            proposed_content = original_content

    # Parse hunks from the calculated diff
    parsed_hunks = parse_unified_diff(final_diff)
    lines_added = sum(1 for line in final_diff.splitlines() if line.startswith("+") and not line.startswith("+++"))
    lines_removed = sum(1 for line in final_diff.splitlines() if line.startswith("-") and not line.startswith("---"))
    proposed_sha256 = compute_sha256(proposed_content)

    # Generate unique patch ID
    patch_id = f"patch-{uuid.uuid4().hex[:12]}"
    now_iso = datetime.now(timezone.utc).isoformat()

    metadata = PatchMetadata(
        patch_id=patch_id,
        file_path=rel_path_str,
        workspace_root=str(ws_root),
        timestamp=now_iso,
        lines_added=lines_added,
        lines_removed=lines_removed,
        hunk_count=len(parsed_hunks),
        original_sha256=original_sha256,
        proposed_sha256=proposed_sha256,
        is_new_file=is_new_file,
        is_deletion=(proposed_content == "" and not is_new_file),
    )

    preview_summary = (
        f"Patch ID: {patch_id}\n"
        f"Target: {rel_path_str} ({'+' if is_new_file else ''}{'NEW' if is_new_file else 'EDIT'})\n"
        f"Hunks: {len(parsed_hunks)} | Lines Added: +{lines_added} | Lines Removed: -{lines_removed}\n"
        f"Clean Apply: {can_apply_cleanly}\n"
    )

    result = PatchProposalResult(
        patch_id=patch_id,
        file_path=rel_path_str,
        diff=final_diff,
        metadata=metadata,
        can_apply_cleanly=can_apply_cleanly,
        hunks=parsed_hunks,
        proposed_content=proposed_content,
        conflict_reason=conflict_reason,
        preview_summary=preview_summary,
    )

    # Cache proposal in in-memory registry for seamless apply referencing
    _PATCH_CACHE[patch_id] = result

    return result


# ==============================================================================
# 8. APPLY_PATCH (GUARDED, BACKED-UP, ATOMIC, SYNTAX-VERIFIED)
# ==============================================================================

def apply_patch(
    file_path: Optional[Union[str, Path]] = None,
    new_content: Optional[str] = None,
    patch_diff: Optional[str] = None,
    patch_id: Optional[str] = None,
    workspace_root: Optional[Union[str, Path]] = None,
    confirm: bool = False,
    backup_suffix: str = ".bak",
    run_syntax_check: bool = True,
    raise_errors: bool = False,
) -> PatchApplyResult:
    """Apply proposed patch with explicit confirmation, backup, and syntax auto-rollback.

    Pipeline:
    1. Confirmation Gate: Requires confirm=True. Aborts otherwise.
    2. Path Sandbox Gate: Verifies target is strictly within workspace_root.
    3. Source Resolution: Resolves content from patch_id (cache) or direct parameters.
    4. Safety Backup: Copies target to '<file_path>.bak' via shutil.copy2.
    5. Atomic Write: Writes content using a temporary file and atomic replace.
    6. Syntax Verification Gate: Evaluates AST/schema.
    7. Auto-Rollback: On syntax failure, restores original file from .bak automatically.

    Args:
        file_path: Target file path (optional if patch_id is provided).
        new_content: Direct proposed content.
        patch_diff: Unified diff to apply.
        patch_id: Identifier of a previously generated proposal.
        workspace_root: Workspace root directory.
        confirm: Explicit execution confirmation flag. Must be True to apply.
        backup_suffix: Suffix for safety backup file (default: ".bak").
        run_syntax_check: Whether to run post-application syntax checks (default: True).
        raise_errors: Whether to raise exceptions on failures instead of returning result.

    Returns:
        PatchApplyResult with execution, backup, and rollback details.

    Raises:
        ConfirmationRequiredError: If confirm is False and raise_errors is True.
        WorkspaceSecurityError: If path escapes workspace and raise_errors is True.
        PatchConflictError: If diff cannot be applied and raise_errors is True.
        SyntaxVerificationError: If syntax check fails and raise_errors is True.
    """
    effective_patch_id = patch_id or "adhoc"

    # 1. CONFIRMATION GATE
    if not confirm:
        msg = (
            "Explicit confirmation required (confirm=True) to apply patch. "
            "Safety protocol blocked unconfirmed write operation."
        )
        if raise_errors:
            raise ConfirmationRequiredError(msg)
        return PatchApplyResult(
            success=False,
            patch_id=effective_patch_id,
            file_path=str(file_path or ""),
            backup_path=None,
            syntax_check_passed=False,
            syntax_error=None,
            rolled_back=False,
            applied_hunks=0,
            total_hunks=0,
            message=msg,
        )

    # 2. RESOLVE PROPOSAL FROM CACHE OR PARAMETERS
    cached_proposal: Optional[PatchProposalResult] = None
    if patch_id:
        cached_proposal = get_cached_proposal(patch_id)
        if not cached_proposal:
            msg = f"Patch ID '{patch_id}' not found in proposal registry."
            if raise_errors:
                raise PatchError(msg)
            return PatchApplyResult(
                success=False,
                patch_id=patch_id,
                file_path=str(file_path or ""),
                backup_path=None,
                syntax_check_passed=False,
                syntax_error=None,
                rolled_back=False,
                applied_hunks=0,
                total_hunks=0,
                message=msg,
            )

    target_file_param = file_path or (cached_proposal.file_path if cached_proposal else None)
    if not target_file_param:
        msg = "No target file specified. Provide file_path or a valid patch_id."
        if raise_errors:
            raise ValueError(msg)
        return PatchApplyResult(
            success=False,
            patch_id=effective_patch_id,
            file_path="",
            backup_path=None,
            syntax_check_passed=False,
            syntax_error=None,
            rolled_back=False,
            applied_hunks=0,
            total_hunks=0,
            message=msg,
        )

    # 3. WORKSPACE SANDBOX VERIFICATION
    try:
        target_path, ws_root = validate_workspace_path(target_file_param, workspace_root)
    except WorkspaceSecurityError as e:
        if raise_errors:
            raise
        return PatchApplyResult(
            success=False,
            patch_id=effective_patch_id,
            file_path=str(target_file_param),
            backup_path=None,
            syntax_check_passed=False,
            syntax_error=None,
            rolled_back=False,
            applied_hunks=0,
            total_hunks=0,
            message=str(e),
        )

    is_new_file = not target_path.exists()
    rel_path_str = str(target_path.relative_to(ws_root)).replace("\\", "/")

    # Read current content
    original_content = ""
    if not is_new_file:
        try:
            original_content = target_path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            msg = f"Cannot patch binary file: {target_path}"
            if raise_errors:
                raise BinaryFileError(msg)
            return PatchApplyResult(
                success=False,
                patch_id=effective_patch_id,
                file_path=rel_path_str,
                backup_path=None,
                syntax_check_passed=False,
                syntax_error=None,
                rolled_back=False,
                applied_hunks=0,
                total_hunks=0,
                message=msg,
            )

    # Determine final content to write
    content_to_write: str = ""
    total_hunks = 0
    applied_hunks = 0

    if cached_proposal:
        content_to_write = cached_proposal.proposed_content
        total_hunks = len(cached_proposal.hunks)
        applied_hunks = total_hunks if cached_proposal.can_apply_cleanly else 0
        if not cached_proposal.can_apply_cleanly:
            msg = f"Cached patch '{patch_id}' contains conflicts: {cached_proposal.conflict_reason}"
            if raise_errors:
                raise PatchConflictError(msg)
            return PatchApplyResult(
                success=False,
                patch_id=effective_patch_id,
                file_path=rel_path_str,
                backup_path=None,
                syntax_check_passed=False,
                syntax_error=None,
                rolled_back=False,
                applied_hunks=0,
                total_hunks=total_hunks,
                message=msg,
            )
    elif new_content is not None:
        content_to_write = new_content
        diff_preview = propose_patch(target_path, new_content=new_content, workspace_root=ws_root)
        total_hunks = len(diff_preview.hunks)
        applied_hunks = total_hunks
    elif patch_diff is not None:
        hunks = parse_unified_diff(patch_diff)
        total_hunks = len(hunks)
        patched_text, success, conflict = apply_hunks_to_content(original_content, hunks)
        if not success:
            msg = f"Patch conflict during hunk application: {conflict}"
            if raise_errors:
                raise PatchConflictError(msg)
            return PatchApplyResult(
                success=False,
                patch_id=effective_patch_id,
                file_path=rel_path_str,
                backup_path=None,
                syntax_check_passed=False,
                syntax_error=None,
                rolled_back=False,
                applied_hunks=0,
                total_hunks=total_hunks,
                message=msg,
            )
        content_to_write = patched_text
        applied_hunks = total_hunks
    else:
        msg = "Must supply 'new_content', 'patch_diff', or a valid 'patch_id'."
        if raise_errors:
            raise ValueError(msg)
        return PatchApplyResult(
            success=False,
            patch_id=effective_patch_id,
            file_path=rel_path_str,
            backup_path=None,
            syntax_check_passed=False,
            syntax_error=None,
            rolled_back=False,
            applied_hunks=0,
            total_hunks=0,
            message=msg,
        )

    # 4. SAFETY BACKUP CREATION
    backup_path: Optional[Path] = None
    if not is_new_file:
        backup_path = target_path.with_name(f"{target_path.name}{backup_suffix}")
        try:
            shutil.copy2(target_path, backup_path)
        except Exception as e:
            msg = f"Failed to create safety backup '{backup_path}': {str(e)}"
            if raise_errors:
                raise PatchError(msg)
            return PatchApplyResult(
                success=False,
                patch_id=effective_patch_id,
                file_path=rel_path_str,
                backup_path=None,
                syntax_check_passed=False,
                syntax_error=None,
                rolled_back=False,
                applied_hunks=0,
                total_hunks=total_hunks,
                message=msg,
            )

    # 5. ATOMIC DISK WRITE VIA SIBLING TEMPORARY FILE
    target_path.parent.mkdir(parents=True, exist_ok=True)
    temp_file: Optional[Path] = None
    try:
        # Create temp file in same directory to ensure atomic os.replace across filesystem boundaries
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=target_path.parent,
            prefix=f".tmp_patch_{target_path.stem}_",
            delete=False,
        ) as tf:
            tf.write(content_to_write)
            temp_file = Path(tf.name)

        # Atomic replacement
        os.replace(temp_file, target_path)
    except Exception as e:
        # Clean up temp file on failure
        if temp_file and temp_file.exists():
            try:
                temp_file.unlink()
            except OSError:
                pass

        msg = f"Failed during atomic file write: {str(e)}"
        # Restore backup if write failed midway
        if backup_path and backup_path.exists():
            shutil.copy2(backup_path, target_path)

        if raise_errors:
            raise PatchError(msg)
        return PatchApplyResult(
            success=False,
            patch_id=effective_patch_id,
            file_path=rel_path_str,
            backup_path=str(backup_path) if backup_path else None,
            syntax_check_passed=False,
            syntax_error=None,
            rolled_back=True,
            applied_hunks=0,
            total_hunks=total_hunks,
            message=msg,
        )

    # 6. POST-APPLICATION SYNTAX VERIFICATION GATE
    syntax_passed = True
    syntax_err: Optional[str] = None

    if run_syntax_check:
        syntax_passed, syntax_err = verify_syntax(target_path, content_to_write)

        if not syntax_passed:
            # 7. AUTOMATIC ROLLBACK PROTOCOL
            rolled_back = False
            if is_new_file:
                # If newly created, remove the newly created file
                if target_path.exists():
                    target_path.unlink()
                rolled_back = True
            elif backup_path and backup_path.exists():
                # Restore original content from backup copy
                shutil.copy2(backup_path, target_path)
                rolled_back = True

            err_msg = (
                f"Syntax validation failed after patch application ({syntax_err}). "
                f"Safety rollback automatically executed: file restored to original state."
            )
            if raise_errors:
                raise SyntaxVerificationError(err_msg)

            return PatchApplyResult(
                success=False,
                patch_id=effective_patch_id,
                file_path=rel_path_str,
                backup_path=str(backup_path) if backup_path else None,
                syntax_check_passed=False,
                syntax_error=syntax_err,
                rolled_back=rolled_back,
                applied_hunks=0,
                total_hunks=total_hunks,
                message=err_msg,
            )

    return PatchApplyResult(
        success=True,
        patch_id=effective_patch_id,
        file_path=rel_path_str,
        backup_path=str(backup_path) if backup_path else None,
        syntax_check_passed=syntax_passed,
        syntax_error=None,
        rolled_back=False,
        applied_hunks=applied_hunks,
        total_hunks=total_hunks,
        message="Patch applied cleanly, verified, and confirmed.",
    )
